def extract_val(x , data): 

    '''
        Parse input data to compute an interpolated or extrapolated value given a set of specially formatted data points from FLOPS:

                                    |NX0NY   Y1   Y2   Y3   Y4   Y5  . . .|
                                    |   X1  Z11  Z12  Z13  Z14  Z15  . . .|
                                    |   X2  Z21  Z22  Z23  Z24  Z25  . . .|
                                    |   X3  Z31  Z32  Z33  Z34  Z35  . . .|
                                    |   .    .    .    .    .    .   . . .|
                                    
        For reference on these data tables: FLOPS v. 9.0.2 source code -> sfaero.f

        This extract_val function, as well as the corresponding z_val function should only be used for the Aviary FLOPS aero tables. Other data sets may
        break this function.

        Parameters
        ----------
        x : ndarray
            The coordinates to sample the gridded data at. First array element is the point to
            interpolate here. Remaining elements are interpolated on sub tables.

        data : ndarray
            A specially formatted rray containing corresponding x , y , and z coordinate points 
            to which a polynomial is fit to.

            

        Returns
        -------
        new_data : ndarray
                A 1xn array containing all of the requested interpolated/ extrapolated z values.
    '''

    y_pf = data[0 , 1:]                                                                  # create y matrix for polyfit
    x_pf = data[1: , 0]                                                                  # create x matrix for polyfit
    x_pf.flatten()
    val = []                                                                             # initiate empty matrix for storing new z values

    if int(len(x)) == 2:
        x_array = [x[0]]                                                                 # parse x_loc data
        y_array = [x[1]]                                                                 # parse y_loc data 
        length = 1
    else:
        x_array = x[:, 0]                                                                # parse x_loc data
        y_array = x[:, 1]                                                                # parse y_loc data
        length = int(len(x_array))


    for i in range(length):
        x_loc = x_array[i]                                                               # x coordinate for interpolation/extrapolation
        y_loc = y_array[i]                                                               # y coordinate for interpolation/extrapolation
        new_data = z_val(x_loc , y_loc , x_pf , y_pf, data)                              # get new z val

        if isinstance(new_data , np.ndarray):                                            # ensure that the output will be an numpy array
            val.append(new_data[0])
        else:
            val.append(new_data)
            
    return np.array(val , dtype = x.dtype)

#---------- z_val Function ----------
def z_val(x_loc , y_loc , x_pf , y_pf , data):
    
    '''
        Perform a polynomial fit to a set of data points, evaluate the polynomial at the point of interest, then return the z value.
        This function will determine which data exactly is best to use for extrapolation/interpolation from the FLOPS aero tables. This
        z_val function, as well as the corresponding extract_val function should only be used for the Aviary FLOPS aero tables. Other data sets may
        break this function.

        Parameters
        ----------
        x_loc : int
                x location about which to interpolate/extrapolate

        y_loc : int
                y location about which to interpolate/extrapolate

        x_pf : ndarray
            1d data array containing the x coordinates for the data
        
        y_pf : ndarray
            1d data array containing the y coordinates for the data
        
        z_pf : ndarray
            1d data array containing the z coordinates for the data
        
        data : ndarray
            data array from FLOPS
            
            

        Returns
        -------
        z_val : int
                interpolated/extrapolated z value
    '''  

    # closest data point
    closest_line_loc = min(x_pf , key = lambda x: abs(x - x_loc))                                                  # get the x coordinate of the closest line to x_loc 
    line_number = int(list(x_pf).index(closest_line_loc)) + 1                                                      # index of closest line 
    closest_y_loc = min(y_pf , key = lambda y: abs(y - y_loc))                                                     # get the y coordinate of the closest point to y_loc
    closest_y_index = int(list(y_pf).index(closest_y_loc)) + 1                                                     # index of closest line
    error_limit = 0.01                                                                                             # distance error limit for approximating a point to a known line

    # if x is lower than the lower x bound of the data set
    if x_loc < x_pf[0]:                                                                                            # check if x is less than the lower bound of the data
        z_pf = data[line_number, 1:]                                                                               # extract z1 coordinates for polynomial fit
        delta_x_data = abs(x_pf[0] - x_pf[1])                                                                      # del_x between data
        delta_x_loc = abs(x_loc - x_pf[0])                                                                         # del_x between data and x_loc
        Del_X = delta_x_loc / delta_x_data
        z_change_x = data[line_number , closest_y_index] - data[line_number + 1 , closest_y_index]                 # del_z wrt x

        if y_loc <= y_pf[0]:
            next_closest_y = closest_y_index + 1
            z_change_y = data[line_number , closest_y_index] - data[line_number , closest_y_index + 1]
            
            delta_y_data = abs(y_pf[closest_y_index - 1] - y_pf[next_closest_y]) 
            delta_y_loc = abs(y_loc - y_pf[0])
            Del_Y = delta_y_loc / delta_y_data

        elif y_loc >= y_pf[int(len(y_pf) - 1)]:
            next_closest_y = closest_y_index - 2
            z_change_y = data[line_number , closest_y_index] - data[line_number , closest_y_index - 1]    
            
            delta_y_data = abs(y_pf[closest_y_index - 1] - y_pf[next_closest_y]) 
            delta_y_loc = abs(y_loc - y_pf[int(len(y_pf))-1])
            Del_Y = delta_y_loc / delta_y_data

        if y_loc <= y_pf[0] or y_loc >= y_pf[int(len(y_pf) - 1)]:                                                  # check if y is outside of the y bounds of the data set
            z_trend_1 = Del_Y * z_change_y
            z_trend_2 = Del_X * z_change_x
            z_trend = z_trend_1 + z_trend_2
            z_val = z_pf[closest_y_index - 1] + z_trend                                                            # get new z val

        else:
            z_change = data[line_number , closest_y_index] - data[line_number + 1, closest_y_index]
            delta_x_data = abs(x_pf[line_number - 1] - x_pf[line_number]) 
            delta_x_loc = abs(x_loc - x_pf[0])
            Del_x = delta_x_loc / delta_x_data                                                                     # delta y for z trend approximation
            z_trend = Del_x * z_change                                                                             # get new z val
            z_val = poly_fit(y_pf , z_pf , y_loc) + z_trend

    # if x is within the x bounds of the data set
    elif x_loc >= x_pf[0] and x_loc <= x_pf[int(len(x_pf) - 1)]:                                                   # check if x is within the bounds of the data
        if x_loc < closest_line_loc:
            greater_line_index = line_number - 1                                                                   # get index of first line greater than x
            lesser_line_index = line_number - 2                                                                    # get index of first line less than x
            error_margin = (abs(x_loc - closest_line_loc)) / (x_pf[greater_line_index] - x_pf[lesser_line_index])  # calculate error margin
        elif x_loc > closest_line_loc:
            greater_line_index = line_number                                                                       # get index of first line greater than x
            lesser_line_index = line_number - 1                                                                    # get index of first line less than x
            error_margin = (abs(x_loc - closest_line_loc)) / (x_pf[greater_line_index] - x_pf[lesser_line_index])  # calculate error margin
        else:
            error_margin = 0

        if y_loc >= y_pf[0] and y_loc <= y_pf[int(len(y_pf) - 1)]:                                                 # if y is outside of the y bounds of the data set
            z_pf = data[line_number, 1:]                                                                           # extract z coordinates for polynomial fit
            if error_margin <= error_limit:
                z_val = poly_fit(y_pf , z_pf , y_loc)                                                              # get new z val
            else:                                                                                                  # get next closest line
                if x_loc < closest_line_loc:
                    next_closest_line = line_number - 1
                else:
                    next_closest_line = line_number 
                z_pf_1 = data[line_number , 1:]                                                                    # extract z1 coordinates for polynomial fit
                z_pf_2 = data[next_closest_line + 1 , 1:]                                                          # extract z2 coordinates for polynomial fit
                z_val_1 = poly_fit(y_pf , z_pf_1 , y_loc)                                                          # get new z1 val
                z_val_2 = poly_fit(y_pf , z_pf_2 , y_loc)                                                          # get new z2 val
                z_val = ((z_val_1 + z_val_2) / 2) * error_margin                                                   # get new z val as average of z1 and z2
                Del_Z = (z_val_2 - z_val_1) * error_margin
                z_val = z_val_1 + Del_Z

        else:                                                                                                      # if y is within the y bounds of the data set, get the second closest line to the interp location
            if x_loc < closest_line_loc:
                next_closest_line = line_number - 1
            else:
                next_closest_line = line_number 
            z_pf_1 = data[line_number , 1:]                                                                        # extract z1 coordinates for polynomial fit
            z_pf_2 = data[next_closest_line , 1:]
            if y_loc > y_pf[int(len(y_pf) - 1)]:                                                                   # extract z2 coordinates for polynomial fit
                z_change_1 = z_pf_1[int(len(z_pf_1) - 1)] - z_pf_1[int(len(z_pf_1) - 2)]                           # delta z1
                z_change_2 = z_pf_2[int(len(z_pf_2) - 1)] - z_pf_2[int(len(z_pf_2) - 2)]                           # delta z1
                delta_y_data = abs(y_pf[int(len(y_pf) - 1)] - y_pf[int(len(y_pf) - 2)]) 
                delta_y_loc = abs(y_loc - y_pf[int(len(y_pf))-1])
                Del_Y = delta_y_loc / delta_y_data                                                                 # delta y for z trend approximation
            elif y_loc < y_pf[0]:
                z_change_1 = z_pf_1[0] - z_pf_1[1]                                                                 # delta z1
                z_change_2 = z_pf_2[0] - z_pf_2[1]                                                                 # delta z2
                delta_y_data = abs(y_pf[1] - y_pf[0]) 
                delta_y_loc = abs(y_pf[0] - y_loc)
                Del_Y = delta_y_loc / delta_y_data                                                                 # delta y for z trend approximation
            z_trend_1 = Del_Y * z_change_1                                                                         # delta z adjusted
            z_trend_2 = Del_Y * z_change_2                                                                         # delta z adjusted
            z_val_1 = z_pf_1[closest_y_index - 1] + z_trend_1                                                      # get new z2 val
            z_val_2 = z_pf_2[closest_y_index - 1] + z_trend_2                                                      # get new z2 val 
            Del_Z = (z_val_2 - z_val_1) * error_margin
            z_val = z_val_1 + Del_Z

    # if x is greater than the upper x bound of the data set
    elif x_loc > x_pf[int(len(x_pf)) - 1]:                                                                         # check if x is greater than the upper bound of the data
        z_pf = data[line_number, 1:]                                                                               # extract z1 coordinates for polynomial fit
        z_change_x = data[line_number , closest_y_index] - data[line_number - 1 , closest_y_index]
        delta_x_data = abs(x_pf[int(len(x_pf))-1] - x_pf[int(len(x_pf))-2])                                        # del_x between data
        delta_x_loc = abs(x_loc - x_pf[int(len(x_pf))-1])                                                          # del_x between data and x_loc
        Del_X = delta_x_loc / delta_x_data

        if y_loc <= y_pf[0]:
            next_closest_y = closest_y_index + 1
            z_change_y = data[line_number , closest_y_index] - data[line_number , closest_y_index + 1]
            
            delta_y_data = abs(y_pf[closest_y_index - 1] - y_pf[next_closest_y]) 
            delta_y_loc = abs(y_loc - y_pf[0])
            Del_Y = delta_y_loc / delta_y_data

        elif y_loc >= y_pf[int(len(y_pf) - 1)]:
            next_closest_y = closest_y_index - 2
            z_change_y = data[line_number , closest_y_index] - data[line_number , closest_y_index - 1] 
            
            delta_y_data = abs(y_pf[closest_y_index - 1] - y_pf[next_closest_y]) 
            delta_y_loc = abs(y_loc - y_pf[int(len(y_pf))-1])
            Del_Y = delta_y_loc / delta_y_data

        if y_loc <= y_pf[0] or y_loc >= y_pf[int(len(y_pf) - 1)]:                                                  # check if y is outside of the y bounds of the data set
            z_trend_1 = Del_Y * z_change_y
            z_trend_2 = Del_X * z_change_x
            z_trend = z_trend_1 + z_trend_2
            z_val = z_pf[closest_y_index - 1] + z_trend                                                            # get new z val

        else:
            z_change = data[line_number , closest_y_index] - data[line_number - 1, closest_y_index]                # delta z
            delta_x_data = abs(x_pf[line_number - 1] - x_pf[line_number - 2]) 
            delta_x_loc = abs(x_loc - x_pf[int(len(x_pf))-1])
            Del_x = delta_x_loc / delta_x_data                                                                     # delta y for z trend approximation
            z_trend = Del_x * z_change                                                                             # get new z val
            z_val = poly_fit(y_pf , z_pf , y_loc)  + z_trend

    return z_val

#---------- extrapolate Function ----------
def poly_fit(y , z , y_loc): 

    '''
    Fit a 1D 3rd order polynomial to a given set of data, evaluate the polynomial at the given point, then return the new z val

    Parameters
    ----------
    y : ndarray
        The y-coordinates of the data set.  

    z : ndarray
        The z-coordinates of the data set.  
        
    x_loc : integer
            The x-coordinate used for the point of interpolation/ extrapolation

    y_loc : integer
            The y-coordinate used for the point of interpolation/ extrapolation

            

    Returns
    -------
    z_new : integer
            The z value of the fitted polynomial evaluated at the point (x_loc , y_loc).
    '''
    
    Y = y.flatten()
    A = np.array([Y*0 + 1 , Y , Y**2 , Y**3]).T                                              # create the design matrix A
    B = z.flatten()                                                                          # flatten the target values Z
    coeff, _, _, _ = np.linalg.lstsq(A, B , rcond = -1)                                      # solve for the coefficients

    z_new = coeff[0] + (coeff[1] * y_loc) + (coeff[2] * y_loc**2) + (coeff[3] * y_loc**3)    # evaluate the new polynomial

    return z_new 



